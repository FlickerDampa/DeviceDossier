        public static void Save(AuditReport report, string path)
        {
            File.WriteAllText(path, Render(report), new UTF8Encoding(false));
        }

        public static string Render(AuditReport report)
        {
            var sb = new StringBuilder(256 * 1024);
            string device = report.DeviceName ?? Environment.MachineName;
            string generated = report.Generated.ToString("dd MMM yyyy, HH:mm", CultureInfo.InvariantCulture);

            sb.Append("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
            sb.Append("<meta name=\"generator\" content=\"").Append(E(report.ToolName)).Append(" ").Append(E(report.ToolVersion)).Append("\">\n");
            sb.Append("<link rel=\"icon\" href=\"").Append(Favicon).Append("\">\n");
            sb.Append("<title>").Append(E(device)).Append(" - Device Dossier</title>\n<style>").Append(Css).Append("</style>\n</head>\n<body>\n");

            sb.Append("<header class=\"top\">\n<div class=\"brand\">").Append(Logo).Append("<span>DeviceDossier</span></div>\n");
            sb.Append("<div class=\"title\"><h1>").Append(E(device)).Append("</h1><p class=\"meta\">Audited ").Append(E(generated))
              .Append(" &middot; run as ").Append(E(report.RunAsUser))
              .Append(report.RanAsAdmin ? " (administrator)" : " <span class=\"pill warn\">limited mode</span>")
              .Append(" &middot; ").Append(E(report.ToolName)).Append(" ").Append(E(report.ToolVersion)).Append("</p></div>\n");
            sb.Append("<div class=\"tools\"><label class=\"search\"><input id=\"q\" type=\"text\" placeholder=\"Search the whole report\" autocomplete=\"off\"><span id=\"hits\"></span></label>")
              .Append("<button type=\"button\" id=\"print\">Print / PDF</button></div>\n</header>\n");

            sb.Append("<nav class=\"tabs\" role=\"tablist\">\n");
            sb.Append(TabButton("summary", "Summary", SectionState.Ok));
            foreach (var tab in ReportLayout.Tabs)
            {
                var sections = tab.Sections.Select(id => report[id]).Where(s => s != null).ToList();
                if (sections.Count == 0) continue;
                sb.Append(TabButton(Slug(tab.Header), tab.Header, ReportLayout.Worst(sections)));
            }
            sb.Append("</nav>\n<main>\n");

            RenderSummary(sb, report);
            foreach (var tab in ReportLayout.Tabs)
            {
                var sections = tab.Sections.Select(id => report[id]).Where(s => s != null).ToList();
                if (sections.Count == 0) continue;
                sb.Append("<section class=\"panel\" id=\"").Append(Slug(tab.Header)).Append("\" role=\"tabpanel\">\n");
                sb.Append("<h2 class=\"panel-title\">").Append(E(tab.Header)).Append("</h2>\n");
                foreach (var s in sections) RenderSection(sb, s);
                sb.Append("</section>\n");
            }

            sb.Append("<p id=\"none\" class=\"empty\" hidden>Nothing in this report matches your search.</p>\n</main>\n");
            sb.Append("<footer>Generated by ").Append(E(report.ToolName)).Append(" ").Append(E(report.ToolVersion)).Append(" on ").Append(E(generated))
              .Append(". This file is a point-in-time snapshot of ").Append(E(device)).Append(" and contains sensitive inventory data - store and share it accordingly.</footer>\n");
            sb.Append("<script>").Append(Script).Append("</script>\n</body>\n</html>\n");
            return sb.ToString();
        }

        private static string TabButton(string id, string text, SectionState state)
        {
            string dot = state == SectionState.Ok ? "" : "<i class=\"dot " + StateClass(state) + "\" title=\"" + state + "\"></i>";
            return "<button type=\"button\" role=\"tab\" data-tab=\"" + id + "\">" + E(text) + dot + "</button>\n";
        }

        private static void RenderSummary(StringBuilder sb, AuditReport report)
        {
            sb.Append("<section class=\"panel\" id=\"summary\" role=\"tabpanel\">\n");

            int ok = report.Sections.Count(s => s.State == SectionState.Ok);
            int warn = report.Sections.Count(s => s.State == SectionState.Warning);
            int err = report.Sections.Count(s => s.State == SectionState.Error);
            int skip = report.Sections.Count(s => s.State == SectionState.Skipped);
            sb.Append("<div class=\"health\">")
              .Append(Stat(ok, "complete", "ok"))
              .Append(warn > 0 ? Stat(warn, "with warnings", "warn") : "")
              .Append(err > 0 ? Stat(err, "with errors", "err") : "")
              .Append(skip > 0 ? Stat(skip, "skipped", "skip") : "")
              .Append("</div>\n");

            sb.Append("<div class=\"tiles\">\n");
            foreach (var t in ReportLayout.Summary(report))
            {
                sb.Append("<div class=\"tile\"><b class=\"tag\">").Append(E(t.Tag)).Append("</b><div><small>").Append(E(t.Label))
                  .Append("</small><strong title=\"").Append(E(t.Value)).Append("\">").Append(E(t.Value)).Append("</strong><span title=\"")
                  .Append(E(t.Detail)).Append("\">").Append(E(t.Detail)).Append("</span></div></div>\n");
            }
            sb.Append("</div>\n");

            string patch = ReportLayout.LatestSecurityUpdate(report);
            if (!string.IsNullOrEmpty(patch))
                sb.Append("<h3>Latest security update</h3>\n<p class=\"card mono\">").Append(E(patch)).Append("</p>\n");

            var issues = report.Sections.Where(s => s.State == SectionState.Warning || s.State == SectionState.Error).ToList();
            if (issues.Count > 0)
            {
                sb.Append("<h3>Needs attention</h3>\n");
                foreach (var s in issues)
                    sb.Append("<p class=\"banner ").Append(StateClass(s.State)).Append("\"><b>").Append(E(ReportLayout.Pretty(s.Title))).Append(":</b> ")
                      .Append(E(ReportLayout.StateText(s))).Append("</p>\n");
            }
            sb.Append("</section>\n");
        }

        private static string Stat(int n, string label, string cls)
        {
            return "<span class=\"stat " + cls + "\"><b>" + n + "</b> section" + (n == 1 ? "" : "s") + " " + label + "</span>";
        }

        private static void RenderSection(StringBuilder sb, Section s)
        {
            sb.Append("<article class=\"sec\" id=\"sec-").Append(E(s.Id)).Append("\">\n<h2><span class=\"num\">").Append(E(s.Number)).Append("</span>")
              .Append(E(ReportLayout.Pretty(s.Title))).Append("</h2>\n");
            string sub = SubTitle(s.Title);
            if (sub.Length > 0) sb.Append("<p class=\"sub\">").Append(E(sub)).Append("</p>\n");
            if (s.State != SectionState.Ok)
                sb.Append("<p class=\"banner ").Append(StateClass(s.State)).Append("\">").Append(E(ReportLayout.StateText(s))).Append("</p>\n");

            foreach (var b in s.Blocks)
            {
                if (!string.IsNullOrEmpty(b.Caption))
                    sb.Append(b.CaptionStyle == CaptionStyle.Italic ? "<p class=\"note\">" : "<h3>").Append(E(b.Caption)).Append(b.CaptionStyle == CaptionStyle.Italic ? "</p>\n" : "</h3>\n");
                if (b.Kind == BlockKind.KeyValue) RenderFields(sb, b);
                else if (b.Rows.Count > 0 && b.Rows.Count <= 4 && b.Headers.Length >= 6) RenderRecords(sb, b);
                else RenderTable(sb, b);
            }
            sb.Append("</article>\n");
        }

        private static string SubTitle(string title)
        {
            int dash = title.IndexOf(" - ", StringComparison.Ordinal);
            return dash > 0 ? title.Substring(dash + 3).Trim() : "";
        }

        private static void RenderFields(StringBuilder sb, Block b)
        {
            sb.Append("<dl class=\"kv\">\n");
            foreach (var f in b.Fields)
                sb.Append("<div data-row><dt>").Append(E(f.Name)).Append("</dt><dd").Append(Fmt.IsNumber(f.Value) ? " class=\"n\"" : "").Append(">")
                  .Append(Value(f.Text)).Append("</dd></div>\n");
            sb.Append("</dl>\n");
        }

        private static void RenderRecords(StringBuilder sb, Block b)
        {
            for (int r = 0; r < b.Rows.Count; r++)
            {
                var row = b.Rows[r];
                sb.Append("<div class=\"record\">");
                if (b.Rows.Count > 1) sb.Append("<h4><span>").Append(r + 1).Append("</span>").Append(E(Fmt.Text(row[0]))).Append("</h4>");
                sb.Append("<dl class=\"kv\">\n");
                for (int c = 0; c < b.Headers.Length; c++)
                {
                    object v = c < row.Length ? row[c] : null;
                    sb.Append("<div data-row><dt>").Append(E(b.Headers[c])).Append("</dt><dd>").Append(Value(Fmt.Text(v))).Append("</dd></div>\n");
                }
                sb.Append("</dl></div>\n");
            }
        }

        private static void RenderTable(StringBuilder sb, Block b)
        {
            sb.Append("<div class=\"tbl\"><table>\n<thead><tr>");
            foreach (var h in b.Headers) sb.Append("<th scope=\"col\">").Append(E(h)).Append("</th>");
            sb.Append("</tr></thead>\n<tbody>\n");
            foreach (var row in b.Rows)
            {
                sb.Append("<tr data-row>");
                for (int c = 0; c < b.Headers.Length; c++)
                {
                    object v = c < row.Length ? row[c] : null;
                    sb.Append(Fmt.IsNumber(v) ? "<td class=\"n\">" : "<td>").Append(Value(Fmt.Text(v))).Append("</td>");
                }
                sb.Append("</tr>\n");
            }
            sb.Append("</tbody></table></div>\n");
            if (b.Rows.Count > 8) sb.Append("<p class=\"count\">").Append(b.Rows.Count.ToString(CultureInfo.InvariantCulture)).Append(" rows</p>\n");
        }

        private static string Value(string text)
        {
            if (string.IsNullOrEmpty(text)) return "<span class=\"na\">&ndash;</span>";
            string encoded = E(text).Replace("\r\n", "<br>").Replace("\n", "<br>");
            if (text.StartsWith("ERROR", StringComparison.Ordinal)) return "<span class=\"bad\">" + encoded + "</span>";
            if (text.StartsWith(Fmt.NA, StringComparison.Ordinal) || text.StartsWith("Skipped", StringComparison.Ordinal)) return "<span class=\"na\">" + encoded + "</span>";
            return encoded;
        }

        private static string StateClass(SectionState s)
        {
            switch (s)
            {
                case SectionState.Error: return "err";
                case SectionState.Warning: return "warn";
                case SectionState.Skipped: return "skip";
                default: return "ok";
            }
        }

        private static string Slug(string text)
        {
            var sb = new StringBuilder();
            foreach (char c in text.ToLowerInvariant()) sb.Append(char.IsLetterOrDigit(c) ? c : '-');
            return sb.ToString().Trim('-');
        }

